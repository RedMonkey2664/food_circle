/**
 * pnpm seed:osm:sql <out.sql>
 *
 * Writes the cached OSM seed (data/raw/, from `pnpm seed:osm`) as one idempotent SQL file,
 * for loading a hosted database through the Supabase SQL editor without handling the
 * secret key. Same mapping as scripts/seed-osm.ts. Re-running is safe: areas and brands are
 * upserted by slug, places by osm_id, and existing places keep their location, area and
 * status (only name and tags refresh).
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import {
  REGIONS,
  dedupeAreas,
  toAreaRow,
  toPlaceRow,
  type AreaRow,
  type BrandDef,
  type OsmElement,
  type PlaceRow,
} from './osm/transform';

const out = process.argv[2];
if (!out) {
  console.error('Usage: pnpm seed:osm:sql <out.sql>');
  process.exit(1);
}

function load(name: string): OsmElement[] {
  const file = join('data', 'raw', `osm-${name}.json`);
  if (!existsSync(file))
    throw new Error(`${file} missing: run "pnpm seed:osm" once to download it.`);
  return (JSON.parse(readFileSync(file, 'utf8')) as { elements: OsmElement[] }).elements;
}

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const arr = (xs: readonly string[]) =>
  xs.length ? `array[${xs.map(q).join(',')}]::text[]` : `'{}'::text[]`;
const pt = (lat: number, lng: number) =>
  `extensions.st_setsrid(extensions.st_makepoint(${lng}, ${lat}), 4326)`;

const brands = JSON.parse(readFileSync(join('data', 'brands.json'), 'utf8')) as BrandDef[];
const places = load('places')
  .map((el) => toPlaceRow(el, brands))
  .filter((p): p is PlaceRow => p !== null);
const areas = dedupeAreas(
  load('areas')
    .map(toAreaRow)
    .filter((a): a is AreaRow => a !== null),
);
const brandRows = [
  ...new Map(places.flatMap((p) => (p.brand ? [[p.brand.slug, p.brand]] : []))).values(),
];

const lines: string[] = [
  '-- Food Circle OSM seed (generated by scripts/osm-to-sql.ts). Data (c) OpenStreetMap contributors, ODbL.',
  'begin;',
  'set local search_path = public, extensions;',
  '',
  '-- regions',
  `insert into public.areas (slug, name, kind) values`,
  Object.entries(REGIONS)
    .map(([slug, name]) => `  (${q(slug)}, ${q(name)}, 'region')`)
    .join(',\n'),
  'on conflict (slug) do update set name = excluded.name;',
  '',
  '-- suburbs and neighbourhoods',
  'insert into public.areas (slug, name, kind, parent_id, centroid) values',
  areas
    .map(
      (a) =>
        `  (${q(a.slug)}, ${q(a.name)}, ${q(a.kind)}, ${
          a.region ? `(select id from public.areas where slug = ${q(a.region)})` : 'null'
        }, ${pt(a.lat, a.lng)})`,
    )
    .join(',\n'),
  'on conflict (slug) do update set name = excluded.name, kind = excluded.kind,',
  '  parent_id = excluded.parent_id, centroid = excluded.centroid;',
  '',
  '-- brands (chains, for the chain cap)',
  'insert into public.brands (slug, name) values',
  brandRows.map((b) => `  (${q(b.slug)}, ${q(b.name)})`).join(',\n'),
  'on conflict (slug) do nothing;',
  '',
];

// Places in batches so each statement stays a reasonable size.
for (let i = 0; i < places.length; i += 400) {
  const batch = places.slice(i, i + 400);
  lines.push(
    'insert into public.places (osm_id, name, aliases, type, diet_flags, cuisine_tags, brand_id, source, geom, status) values',
    batch
      .map(
        (p) =>
          `  (${q(p.osm_id)}, ${q(p.name)}, ${arr(p.aliases)}, ${q(p.type)}::place_type, ${arr(p.diet_flags)}, ${arr(
            p.cuisine_tags,
          )}, ${p.brand ? `(select id from public.brands where slug = ${q(p.brand.slug)})` : 'null'}, 'osm', ${pt(
            p.lat,
            p.lng,
          )}::geography, 'confirmed')`,
      )
      .join(',\n'),
    'on conflict (osm_id) do update set name = excluded.name, aliases = excluded.aliases, type = excluded.type,',
    '  diet_flags = excluded.diet_flags, cuisine_tags = excluded.cuisine_tags, brand_id = excluded.brand_id;',
    '',
  );
}

lines.push(
  '-- link neighbourhoods to suburbs and re-resolve any place pinned to a neighbourhood',
  'select public.admin_refresh_place_areas();',
  'commit;',
  '',
  "select count(*) as places, count(area_id) as with_area, (select count(*) from public.areas) as areas from public.places where source = 'osm';",
);

writeFileSync(out, lines.join('\n'));
console.log(
  `wrote ${out}: ${places.length} places, ${areas.length} areas, ${brandRows.length} brands`,
);
